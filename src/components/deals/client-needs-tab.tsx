export function ClientNeedsTab({
  dealId,
  needs,
  loanCategoryProducts,
  allProducts,
  currentProductId,
  hasBorrowerEmail,
  remindersPaused,
  reminderIntervalHours,
  hasAcceptedProduct,
  catalog,
}: {
  dealId: string;
  needs: ClientNeed[];
  loanCategoryProducts: { id: string; label: string }[];
  allProducts: { id: string; label: string }[];
  currentProductId: string | null;
  hasBorrowerEmail: boolean;
  remindersPaused: boolean;
  reminderIntervalHours: number;
  hasAcceptedProduct: boolean;
  catalog: DealCatalogItem[];
}) {
  const [selectedIds, setSelectedIds] = useState<Set<string>>(new Set());
  const [activeTab, setActiveTab] = useState<"docs" | "esign">("docs");

  const docsNeeds = needs.filter((n) => !ESIGN_NEED_TYPES.has(n.needType));
  const esignNeeds = needs.filter((n) => ESIGN_NEED_TYPES.has(n.needType));
  const visibleNeeds = activeTab === "docs" ? docsNeeds : esignNeeds;

  const selectedNeeds = needs.filter((n) => selectedIds.has(n.id) && !n.onHoldAt);
  // "Select all" only ever touches the tab you're looking at — flipping to
  // the other tab shouldn't silently grab (or drop) items you can't see.
  const allVisibleSelected = visibleNeeds.length > 0 && visibleNeeds.every((n) => selectedIds.has(n.id));

  function toggleAll(checked: boolean) {
    setSelectedIds((prev) => {
      const next = new Set(prev);
      for (const n of visibleNeeds) {
        if (checked) next.add(n.id);
        else next.delete(n.id);
      }
      return next;
    });
  }

  function toggleOne(id: string, checked: boolean) {
    setSelectedIds((prev) => {
      const next = new Set(prev);
      if (checked) next.add(id);
      else next.delete(id);
      return next;
    });
  }

  return (
    <div className="space-y-4">
      {!hasAcceptedProduct && (
        <p className="text-sm text-muted-foreground">
          Client needs auto-populate once a term sheet is accepted, or click Auto Generate below
          to pull in a specific lender&apos;s checklist for this loan type right now. You can also
          add items manually.
        </p>
      )}

      <div className="flex flex-wrap items-center justify-between gap-2">
        <label className="flex items-center gap-2 text-sm">
          <Checkbox
            checked={allVisibleSelected}
            onCheckedChange={(v) => toggleAll(v === true)}
            disabled={visibleNeeds.length === 0}
          />
          Select all
        </label>
        <div className="flex flex-wrap gap-2">
          <AutoGenerateDialog dealId={dealId} products={loanCategoryProducts} currentProductId={currentProductId} />
          <div className="inline-flex">
            <SendToBorrowerDialog
              dealId={dealId}
              selectedNeeds={selectedNeeds}
              hasBorrowerEmail={hasBorrowerEmail}
              triggerClassName="rounded-r-none"
            />
            <ReminderMenu
              dealId={dealId}
              remindersPaused={remindersPaused}
              reminderIntervalHours={reminderIntervalHours}
            />
          </div>
          <MoreActionsMenu dealId={dealId} catalog={catalog} allProducts={allProducts} needs={needs} />
        </div>
      </div>

      <Tabs value={activeTab} onValueChange={(v) => setActiveTab(v as "docs" | "esign")}>
        <TabsList>
          <TabsTrigger value="docs">Docs &amp; Forms ({docsNeeds.length})</TabsTrigger>
          <TabsTrigger value="esign">E-sign ({esignNeeds.length})</TabsTrigger>
        </TabsList>

        <TabsContent value="docs" className="space-y-2 pt-2">
          {docsNeeds.map((need) => (
            <ClientNeedRow
              key={need.id}
              dealId={dealId}
              need={need}
              selected={selectedIds.has(need.id)}
              onToggleSelected={(checked) => toggleOne(need.id, checked)}
            />
          ))}
          {docsNeeds.length === 0 && <p className="text-sm text-muted-foreground">No docs or forms yet.</p>}
        </TabsContent>

        <TabsContent value="esign" className="space-y-2 pt-2">
          {esignNeeds.map((need) => (
            <ClientNeedRow
              key={need.id}
              dealId={dealId}
              need={need}
              selected={selectedIds.has(need.id)}
              onToggleSelected={(checked) => toggleOne(need.id, checked)}
            />
          ))}
          {esignNeeds.length === 0 && <p className="text-sm text-muted-foreground">No e-sign tasks yet.</p>}
        </TabsContent>
      </Tabs>
    </div>
  );
}
