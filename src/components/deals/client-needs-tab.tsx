function CopyUploadLinkItem({ dealId }: { dealId: string }) {
  async function handleClick() {
    try {
      const link = await getOrCreateBorrowerUploadLink(dealId);
      await navigator.clipboard.writeText(link);
      toast.success("Upload link copied");
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "Couldn't get the upload link.");
    }
  }

  return <DropdownMenuItem onClick={handleClick}>Copy upload link</DropdownMenuItem>;
}

// Client-need sets are scoped to lender + loan category (a specific
// product), not the loan category alone — different lenders genuinely want
// different things for the same loan type (one wants a 1003, another has
// their own application). So this asks which lender's product to pull the
// checklist from, defaulting to the deal's own product once one is chosen.
function AutoGenerateDialog({
  dealId,
  products,
  currentProductId,
}: {
  dealId: string;
  products: { id: string; label: string }[];
  currentProductId: string | null;
}) {
  const router = useRouter();
  const [open, setOpen] = useState(false);
  const [productId, setProductId] = useState(currentProductId ?? "");
  const [pending, startTransition] = useTransition();
  const [error, setError] = useState<string | null>(null);

  function handleOpenChange(next: boolean) {
    setOpen(next);
    if (next) {
      setProductId(currentProductId ?? "");
      setError(null);
    }
  }

  function handleGenerate() {
    if (!productId) {
      setError("Choose a lender's product first");
      return;
    }
    setError(null);
    startTransition(async () => {
      try {
        await autoGenerateClientNeedsForProduct(dealId, productId);
        setOpen(false);
        toast.success("Client needs generated");
        router.refresh();
      } catch (err) {
        const message = err instanceof Error ? err.message : "Couldn't auto-generate client needs.";
        setError(message);
        toast.error(message);
      }
    });
  }

  return (
    <Dialog open={open} onOpenChange={handleOpenChange}>
      <DialogTrigger asChild>
        <Button type="button" variant="outline" size="sm">
          Auto Generate
        </Button>
      </DialogTrigger>
      <DialogContent>
        <DialogHeader>
          <DialogTitle>Auto-generate client needs</DialogTitle>
        </DialogHeader>
        <div className="space-y-4">
          <p className="text-sm text-muted-foreground">
            Pulls that lender&apos;s checklist for this loan type onto the deal — every lender can
            have a slightly different set (a 1003 vs. their own application, for example).
          </p>
          {products.length === 0 ? (
            <p className="text-sm text-muted-foreground">
              No lenders have a product set up for this loan category yet.
            </p>
          ) : (
            <Select value={productId} onValueChange={setProductId}>
              <SelectTrigger className="w-full">
                <SelectValue placeholder="Choose a lender's product" />
              </SelectTrigger>
              <SelectContent>
                {products.map((p) => (
                  <SelectItem key={p.id} value={p.id}>
                    {p.label}
                  </SelectItem>
                ))}
              </SelectContent>
            </Select>
          )}
          {error && <p className="text-sm text-destructive">{error}</p>}
          <Button type="button" className="w-full" disabled={pending || products.length === 0} onClick={handleGenerate}>
            {pending ? "Generating…" : "Generate"}
          </Button>
        </div>
      </DialogContent>
    </Dialog>
  );
}

function AttachDocumentButton({ dealId, needId }: { dealId: string; needId: string }) {
  const router = useRouter();
  const inputRef = useRef<HTMLInputElement>(null);
  const [pending, startTransition] = useTransition();
  const [error, setError] = useState<string | null>(null);

  function handleChange(e: React.ChangeEvent<HTMLInputElement>) {
    const files = e.target.files;
    if (!files || files.length === 0) return;
    setError(null);
    const formData = new FormData();
    for (const file of Array.from(files)) formData.append("file", file);
    startTransition(async () => {
      try {
        await attachDocumentToClientNeed(dealId, needId, formData);
        toast.success("Document uploaded");
        router.refresh();
      } catch (err) {
        const message = err instanceof Error ? err.message : "Couldn't upload those files.";
        setError(message);
        toast.error(message);
      } finally {
        if (inputRef.current) inputRef.current.value = "";
      }
    });
  }

  return (
    <div className="flex flex-col items-start gap-1">
      <input ref={inputRef} type="file" multiple className="hidden" onChange={handleChange} />
      <Button type="button" size="sm" variant="outline" disabled={pending} onClick={() => inputRef.current?.click()}>
        {pending ? "Uploading…" : "Attach documents"}
      </Button>
      {error && <p className="text-xs text-destructive">{error}</p>}
    </div>
  );
}

// Manual only, on purpose — never runs on its own. Reviews every document
// currently in this need; results (and the follow-up chat) are read in the
// document viewer, right next to the document they're about, not here.
function AiReviewButton({ dealId, needId }: { dealId: string; needId: string }) {
  const router = useRouter();
  const [pending, startTransition] = useTransition();

  function handleClick() {
    startTransition(async () => {
      try {
        const result = await reviewClientNeedDocuments(dealId, needId);
        toast.success(
          result.totalFlags > 0
            ? `Reviewed — ${result.totalFlags} thing${result.totalFlags === 1 ? "" : "s"} flagged`
            : "Reviewed — nothing flagged"
        );
        if (result.errors.length) toast.error(String(result.errors[0]));
        router.refresh();
      } catch (err) {
        toast.error(err instanceof Error ? err.message : "AI review failed — try again.");
      }
    });
  }

  return (
    <Button type="button" size="sm" variant="outline" disabled={pending} onClick={handleClick}>
      <Sparkles className="size-3.5" />
      {pending ? "Reviewing…" : "AI Review"}
    </Button>
  );
}

